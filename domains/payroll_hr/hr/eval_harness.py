# domains/payroll_hr/hr/eval_harness.py — ground-truth evaluation of the
# DEPLOYED rules -> ML decision layers, via the shared engine in
# core/eval/base_fraud_eval_harness.py (see that module's docstring for
# why this is generalized rather than copy-pasted from
# domains/banking/fraud/eval_harness.py, which pioneered this shape).
#
# Single-tier only (EMSCAD schema) — HR's fraud detector stays single-tier
# permanently, an accepted gap, not a pending item (no Tier 2 dataset
# search planned).
#
# Requires domains/payroll_hr/hr/data/{train,test_holdout}.csv —
# regenerate with data/prepare_data.py first if missing (not committed).
#
# Usage (from the prism/ repo root, as a module so `core`/`domains` resolve):
#     python -m domains.payroll_hr.hr.eval_harness                  # deterministic layers only (free)
#     python -m domains.payroll_hr.hr.eval_harness --with-llm-sample  # + a small real-LLM sample (costs API calls)
#
# Writes EVAL_RESULTS.md in this domain's folder.

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from core.eval.base_fraud_eval_harness import (
    LlmSampleSpec, TierSpec, render_llm_sample_markdown, render_markdown, run_llm_sample_eval, run_tier_eval,
)
from domains.payroll_hr.hr.agents.hr_detector_agent import HrDetectorAgent
from domains.payroll_hr.hr.tools.posting_scorer import PostingFraudScorer

_HERE = Path(__file__).parent
RESULTS_PATH = _HERE / "EVAL_RESULTS.md"
SYSTEM_MESSAGE = "You are a recruitment-fraud investigator. Be concise and precise."


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--with-llm-sample", action="store_true", help="also run a real-LLM stratified sample")
    args = parser.parse_args()

    tier1 = TierSpec(
        name="Tier 1 — EMSCAD job-posting schema (only tier)",
        holdout_path=str(_HERE / "data" / "test_holdout.csv"),
        label_col="fraudulent",
        rule_fn=HrDetectorAgent.rule_based_filter,
        scorer=PostingFraudScorer(),
    )

    print(f"Evaluating {tier1.name} against {tier1.holdout_path}...")
    r1 = run_tier_eval(tier1)
    print(f"  Combined precision={r1['combined_deterministic']['precision']:.4f} "
          f"recall={r1['combined_deterministic']['recall']:.4f} f1={r1['combined_deterministic']['f1']:.4f}")

    markdown = render_markdown(
        "HR (job-posting fraud)",
        "Generated by `eval_harness.py` against the EMSCAD temporal holdout the model never trained "
        "on, at its real base rate (see `data/prepare_data.py`). Single-tier by design — see "
        "hr_detector_agent.py's module docstring.",
        [r1],
    )

    if args.with_llm_sample:
        # HR's detector agent methods take no `tier` kwarg at all (single
        # tier by design — see module docstring) — bind bare.
        agent = HrDetectorAgent(name="EvalHarnessAgent")
        spec = LlmSampleSpec(
            tier_name=tier1.name, holdout_path=tier1.holdout_path, label_col=tier1.label_col,
            rule_fn=tier1.rule_fn, ml_filter_fn=agent.ml_filter, build_prompt_fn=agent.build_prompt,
            scorer=agent.scorer, llm=agent.llm, system_message=SYSTEM_MESSAGE,
        )
        print(f"\nRunning LLM-sample check for {spec.tier_name}...")
        llm_sample = run_llm_sample_eval(spec)
        markdown += "\n" + render_llm_sample_markdown(r1["base_fraud_rate"], llm_sample, spec.tier_name)

    RESULTS_PATH.write_text(markdown, encoding="utf-8")
    print(f"\nWrote {RESULTS_PATH}")


if __name__ == "__main__":
    sys.exit(main())
