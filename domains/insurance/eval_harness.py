# domains/insurance/eval_harness.py — ground-truth evaluation of the
# DEPLOYED rules -> ML decision layers, both tiers, via the shared engine
# in core/eval/base_fraud_eval_harness.py (see that module's docstring for
# why this is generalized rather than copy-pasted from
# domains/banking/fraud/eval_harness.py, which pioneered this shape).
#
# Requires domains/insurance/data/{train,test_holdout,tier2_train,
# tier2_test_holdout}.csv — regenerate with data/prepare_data.py and
# data/prepare_tier2_data.py first if missing (not committed).
#
# Usage (from the prism/ repo root, as a module so `core`/`domains` resolve):
#     python -m domains.insurance.eval_harness                  # deterministic layers only (free)
#     python -m domains.insurance.eval_harness --with-llm-sample  # + a small real-LLM sample per tier (costs API calls)
#
# Writes EVAL_RESULTS.md in this domain's folder.

from __future__ import annotations

import argparse
import functools
import sys
from pathlib import Path

from core.eval.base_fraud_eval_harness import (
    LlmSampleSpec, TierSpec, render_llm_sample_markdown, render_markdown, run_llm_sample_eval, run_tier_eval,
)
from domains.insurance.agents.healthcare_detector_agent import HealthcareDetectorAgent
from domains.insurance.tools.claim_scorer import ClaimFraudScorer
from domains.insurance.tools.generalizable_scorer import ClaimGeneralizableScorer

_HERE = Path(__file__).parent
RESULTS_PATH = _HERE / "EVAL_RESULTS.md"
SYSTEM_MESSAGE = "You are a healthcare claims fraud investigator. Be concise and precise."


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--with-llm-sample", action="store_true", help="also run a real-LLM stratified sample per tier")
    args = parser.parse_args()

    tier1 = TierSpec(
        name="Tier 1 — Claim_Amount/Approved_Amount schema",
        holdout_path=str(_HERE / "data" / "test_holdout.csv"),
        label_col="Is_Fraud",
        rule_fn=functools.partial(HealthcareDetectorAgent.rule_based_filter, tier="tier1"),
        scorer=ClaimFraudScorer(data_path=str(_HERE / "data" / "train.csv")),
    )
    tier2 = TierSpec(
        name="Tier 2 — Policy_Number/Provider_Patient_Distance schema",
        holdout_path=str(_HERE / "data" / "tier2_test_holdout.csv"),
        label_col="Is_Fraudulent",
        rule_fn=functools.partial(HealthcareDetectorAgent.rule_based_filter, tier="tier2"),
        scorer=ClaimGeneralizableScorer(data_path=str(_HERE / "data" / "tier2_train.csv")),
    )

    print(f"Evaluating {tier1.name} against {tier1.holdout_path}...")
    r1 = run_tier_eval(tier1)
    print(f"  Combined precision={r1['combined_deterministic']['precision']:.4f} "
          f"recall={r1['combined_deterministic']['recall']:.4f} f1={r1['combined_deterministic']['f1']:.4f}")

    print(f"Evaluating {tier2.name} against {tier2.holdout_path}...")
    r2 = run_tier_eval(tier2)
    print(f"  Combined precision={r2['combined_deterministic']['precision']:.4f} "
          f"recall={r2['combined_deterministic']['recall']:.4f} f1={r2['combined_deterministic']['f1']:.4f}")

    markdown = render_markdown(
        "Insurance (claim fraud)",
        "Generated by `eval_harness.py` against each tier's own temporal holdout the model never "
        "trained on, at its real base rate (see `data/prepare_data.py` / `data/prepare_tier2_data.py`).",
        [r1, r2],
    )

    if args.with_llm_sample:
        # Reuses tier1/tier2's own already-loaded scorers (agent.scorer /
        # agent.scorer_generalizable) rather than loading a third pair —
        # same models ml_filter() itself dispatches to per tier.
        agent = HealthcareDetectorAgent(name="EvalHarnessAgent", data_path=str(_HERE / "data" / "train.csv"))
        llm_specs = [
            (r1, LlmSampleSpec(
                tier_name=tier1.name, holdout_path=tier1.holdout_path, label_col=tier1.label_col,
                rule_fn=tier1.rule_fn, ml_filter_fn=functools.partial(agent.ml_filter, tier="tier1"),
                build_prompt_fn=functools.partial(agent.build_prompt, tier="tier1"),
                scorer=agent.scorer, llm=agent.llm, system_message=SYSTEM_MESSAGE,
            )),
            (r2, LlmSampleSpec(
                tier_name=tier2.name, holdout_path=tier2.holdout_path, label_col=tier2.label_col,
                rule_fn=tier2.rule_fn, ml_filter_fn=functools.partial(agent.ml_filter, tier="tier2"),
                build_prompt_fn=functools.partial(agent.build_prompt, tier="tier2"),
                scorer=agent.scorer_generalizable, llm=agent.llm, system_message=SYSTEM_MESSAGE,
            )),
        ]
        markdown += "\n"
        for tier_result, spec in llm_specs:
            print(f"\nRunning LLM-sample check for {spec.tier_name}...")
            llm_sample = run_llm_sample_eval(spec)
            markdown += render_llm_sample_markdown(tier_result["base_fraud_rate"], llm_sample, spec.tier_name)

    RESULTS_PATH.write_text(markdown, encoding="utf-8")
    print(f"\nWrote {RESULTS_PATH}")


if __name__ == "__main__":
    sys.exit(main())
